const FOOD_STORAGE_KEY = 'ayna-admin-food'
const FOOD_SEED_VERSION_KEY = 'ayna-admin-food-seed-version'
const FOOD_UPDATED_EVENT = 'ayna:food-updated'

function notifyFoodUpdated(): void {
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent(FOOD_UPDATED_EVENT))
  }
}

function loadFoodStore(): Food[] {
  if (typeof window === 'undefined') return [...mockFood]

  try {
    const seedVersion = window.localStorage.getItem(FOOD_SEED_VERSION_KEY)
    if (seedVersion !== '2') {
      window.localStorage.setItem(FOOD_SEED_VERSION_KEY, '2')
      window.localStorage.setItem(FOOD_STORAGE_KEY, JSON.stringify(mockFood))
      return [...mockFood]
    }

    const stored = window.localStorage.getItem(FOOD_STORAGE_KEY)
    if (!stored) {
      window.localStorage.setItem(FOOD_STORAGE_KEY, JSON.stringify(mockFood))
      return [...mockFood]
    }

    const parsed = JSON.parse(stored) as Food[]
    if (!Array.isArray(parsed) || parsed.length === 0) {
      window.localStorage.setItem(FOOD_STORAGE_KEY, JSON.stringify(mockFood))
      return [...mockFood]
    }

    return parsed
  } catch {
    return [...mockFood]
  }
}

let foodStore = loadFoodStore()

if (typeof window !== 'undefined') {
  window.addEventListener('storage', (event) => {
    if (event.key === FOOD_STORAGE_KEY) {
      try {
        const stored = window.localStorage.getItem(FOOD_STORAGE_KEY)
        foodStore = stored ? (JSON.parse(stored) as Food[]) : []
      } catch {
        foodStore = []
      }
      notifyFoodUpdated()
    }
  })
}

function persistFoodStore(): void {
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(FOOD_STORAGE_KEY, JSON.stringify(foodStore))
  }
  notifyFoodUpdated()
}

export const foodService = {
  getFood: (): Food[] => {
    foodStore = loadFoodStore()
    return foodStore
  },

  getFoodById: (id: string): Food | undefined => {
    foodStore = loadFoodStore()
    return foodStore.find(food => food.id === id)
  },

  createFood: (food: Food): Food => {
    foodStore = [...foodStore, food]
    persistFoodStore()
    return food
  },

  updateFood: (id: string, updates: Partial<Food>): Food | undefined => {
    const index = foodStore.findIndex(food => food.id === id)
    if (index === -1) return undefined
    const updated = { ...foodStore[index], ...updates }
    foodStore = foodStore.map((food, foodIndex) => foodIndex === index ? updated : food)
    persistFoodStore()
    return updated
  },

  deleteFood: (id: string): boolean => {
    const nextFood = foodStore.filter(food => food.id !== id)
    if (nextFood.length === foodStore.length) return false
    foodStore = nextFood
    persistFoodStore()
    return true
  },

  searchFood: (query: string): Food[] => {
    const lowerQuery = query.toLowerCase()
    return foodStore.filter(food => 
      food.name.toLowerCase().includes(lowerQuery) ||
      food.foodType.toLowerCase().includes(lowerQuery) ||
      food.specialty.toLowerCase().includes(lowerQuery) ||
      food.location.toLowerCase().includes(lowerQuery)
    )
  },

  getFoodByLocation: (location: string): Food[] => {
    return foodStore.filter(food => 
      food.location.toLowerCase().includes(location.toLowerCase())
    )
  },
}
